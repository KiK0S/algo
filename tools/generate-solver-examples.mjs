import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { createSolverExampleSpecs } from "./solver-examples/specs.mjs";

const toolsDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(toolsDirectory, "..");
const catalogPath = path.join(repositoryRoot, "lib", "catalog", "snippets.json");
const compiledCorePath = path.join(repositoryRoot, "extension", "out", "core.js");
const outputRoot = path.join(repositoryRoot, "examples", "templates");
const readmePath = path.join(repositoryRoot, "examples", "README.md");
const checkOnly = process.argv.includes("--check");
const require = createRequire(import.meta.url);

function indent(source, spaces) {
  const prefix = " ".repeat(spaces);
  const lines = source.trim().split("\n");
  const commonIndent = Math.min(
    ...lines.filter((line) => line.trim() !== "").map((line) => line.match(/^\s*/)[0].length)
  );
  return lines
    .map((line) => line.slice(commonIndent))
    .map((line) => line === "" ? "" : `${prefix}${line}`)
    .join("\n");
}

function renderMain(spec) {
  const preamble = spec.preamble?.trim();
  const snippet = spec.render().trim();
  return `// Generated by tools/generate-solver-examples.mjs. Do not edit.
// Catalog entry: ${spec.path}

#include <bits/stdc++.h>
using namespace std;

#ifndef EDULCNI_VIS
#define EDULCNI_VIS(...) ((void)0)
#endif
#ifndef EDULCNI_STEP
#define EDULCNI_STEP(...) ((void)0)
#endif
${preamble ? `\n${preamble}\n` : ""}
${snippet}

int main() {
  ios::sync_with_stdio(false);
  cin.tie(nullptr);

  EDULCNI_VIS(edulcni::live::text("example.scenario", ${JSON.stringify(spec.description)}));
  EDULCNI_STEP("Example scenario initialized");
  EDULCNI_VIS(edulcni::internal::State::instance().delete_widget("example.scenario"));

${indent(spec.mainBody, 2)}

  EDULCNI_VIS(edulcni::live::text("example.status", "All checks passed"));
  EDULCNI_STEP("Example scenario completed");

  cout << "ok\\n";
  return 0;
}
`;
}

function renderReadme(specs, entriesByPath) {
  const rows = specs
    .map((spec) => {
      const entry = entriesByPath.get(spec.path);
      const requirement = spec.requirements?.join(", ") ?? "portable C++17";
      return `| [${spec.name}](templates/${spec.name}/main.cpp) | ${entry.visualization.status} | ${requirement} | ${spec.description} |`;
    })
    .join("\n");

  return `# Runnable template examples

This directory is generated from the canonical algorithm templates and the small
drivers in \`tools/solver-examples\`. Each driver executes real algorithm
operations so \`xeppelin edulcni\` receives visualization frames.

Run an example from its directory:

\`\`\`sh
cd examples/templates/bfs
xeppelin edulcni main
\`\`\`

The empty \`input.in\` is intentional: examples use small deterministic data in
their drivers. The program writes \`ok\` to \`output.out\` after its assertions
pass. Each driver adds scenario start/completion frames around the algorithm's
own operation-level visualization steps. Generated binaries and runtime output
are ignored by Git.

Regenerate or check the committed files from \`extension/\`:

\`\`\`sh
npm run generate:examples
npm run check:examples
npm run test:examples
npm run test:examples:visualization
\`\`\`

PBDS examples require GNU GCC. On macOS, pass a Homebrew compiler explicitly,
for example \`xeppelin edulcni main --compiler g++-15\`.

| Solver | Visualization | Requirement | Scenario |
| --- | --- | --- | --- |
${rows}
`;
}

async function currentText(file) {
  return readFile(file, "utf8").catch(() => undefined);
}

async function synchronize(file, expected, mismatches) {
  const current = await currentText(file);
  if (current === expected) {
    return;
  }
  if (checkOnly) {
    mismatches.push(path.relative(repositoryRoot, file));
    return;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, expected);
}

async function main() {
  const core = require(compiledCorePath);
  const catalog = JSON.parse(await readFile(catalogPath, "utf8"));
  const specs = createSolverExampleSpecs(core).sort((a, b) => a.path.localeCompare(b.path));
  const entriesByPath = new Map(catalog.map((entry) => [entry.path, entry]));
  const specsByPath = new Map();

  for (const spec of specs) {
    if (specsByPath.has(spec.path)) {
      throw new Error(`duplicate example spec: ${spec.path}`);
    }
    if (!entriesByPath.has(spec.path)) {
      throw new Error(`example spec has no template catalog entry: ${spec.path}`);
    }
    specsByPath.set(spec.path, spec);
  }

  const mismatches = [];
  await synchronize(readmePath, renderReadme(specs, entriesByPath), mismatches);
  for (const spec of specs) {
    const directory = path.join(outputRoot, spec.name);
    await synchronize(path.join(directory, "main.cpp"), renderMain(spec), mismatches);
    await synchronize(path.join(directory, "input.in"), spec.input ?? "", mismatches);
  }

  const existingDirectories = await readdir(outputRoot, { withFileTypes: true }).catch(() => []);
  const expectedNames = new Set(specs.map((spec) => spec.name));
  for (const entry of existingDirectories) {
    if (entry.isDirectory() && !expectedNames.has(entry.name)) {
      mismatches.push(path.relative(repositoryRoot, path.join(outputRoot, entry.name)));
    }
  }

  if (mismatches.length > 0) {
    throw new Error(`generated template examples are stale:\n${mismatches.join("\n")}`);
  }
  console.log(`${checkOnly ? "checked" : "generated"} ${specs.length} template examples`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
